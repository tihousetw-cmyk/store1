def get_today_message() -> str:
    """Return a deterministic daily message based on today's date."""
    today = date.today()
    index = today.toordinal() % len(MESSAGES)
    return MESSAGES[index]


def get_random_message() -> str:
    return random.choice(MESSAGES)
